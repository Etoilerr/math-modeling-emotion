pf.heading2(doc, "3.4 时序对齐方法")
pf.body(doc,
    "三模态帧级特征具有不同的时间分辨率：语音帧间隔约32毫秒，"
    "视频帧间隔约200毫秒，文本词间隔则取决于语速。"
    "为使三模态特征可在同一时间轴上比较和融合，本文将所有模态统一池化到50个时间位置。"
    "第i个对齐位置对应的时间区间为："
)
pf.equation(doc, r"\left[\frac{i}{50}T, \frac{i+1}{50}T\right), \quad i=0,1,\dots,49")
pf.body(doc,
    "对每个对齐位置，将落入该时间区间的所有原始帧或词的特征取平均，得到该位置的池化特征："
)
pf.equation(doc, r"\mathbf{x}_m[i] = \frac{1}{|\mathcal{I}_{m,i}|}\sum_{k \in \mathcal{I}_{m,i}} \mathbf{f}_{m,k}")
pf.body(doc,
    "其中I_{m,i}为落入第i个对齐位置的原始帧索引集合，f_{m,k}为第k帧的原始特征向量。"
    "若某对齐位置内无任何原始证据，则以零向量填充。"
    "有效长度定义为非零位置的数量，用于后续构造有效性掩码。"
)
pf.equation(doc, r"\mathbf{M}_m[t] = \mathbb{1}\left(\|\mathbf{x}_m[t]\|_1 > 0\right)")
pf.body(doc,
    "该有效性掩码的构造规则贯穿全文：对任意模态任意时间步，"
    "若特征向量的L1范数大于零则标记为有效，否则标记为填充或缺失。"
    "这一规则简单但有效，能够同时处理尾部填充和任意位置的局部缺失。"
)


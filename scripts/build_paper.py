pf.heading1(doc, "四、问题2——模态缺失鲁棒情感预测")

pf.heading2(doc, "4.1 MA-MFN模型架构")
pf.body(doc,
    "本文提出掩码感知多模态融合网络（Mask-Aware Multimodal Fusion Network, MA-MFN），"
    "用于在模态局部缺失条件下同时完成情感极性三分类和情感强度连续回归[3][12]。"
    "模型输入为三模态对齐特征序列X_m及对应的有效性掩码M_m，"
    "其中m遍历文本、语音和视觉三个模态。模型由四个组件构成：单模态时序编码器、"
    "掩码感知时序池化、门控跨模态融合和双任务输出头。"
)

pf.heading3(doc, "4.1.1 单模态时序编码器")
pf.body(doc,
    "对每个模态，首先通过线性投影将原始特征维度映射到统一的隐层维度d=128："
)
pf.equation(doc, r"\mathbf{Z}_m = \mathrm{GELU}\left(\mathrm{LayerNorm}(\mathbf{W}_m \mathbf{X}_m + \mathbf{b}_m)\right)")
pf.body(doc,
    "随后通过深度可分离一维卷积捕获局部时序上下文，卷积核大小为3，填充为1："
)
pf.equation(doc, r"\mathbf{Z}_m' = \mathbf{Z}_m + \mathrm{Conv1d}_m(\mathbf{Z}_m^{T})^{T}")
pf.body(doc,
    "残差连接和层归一化后得到模态m的时序表示Z_m，形状为批次大小乘以50乘以128。"
    "单模态编码器的设计参考了动态情感专家的思路[7]，"
    "为每个模态独立建模时序模式，避免不同模态在早期融合时互相干扰。"
)

pf.heading3(doc, "4.1.2 掩码感知时序池化")
pf.body(doc,
    "传统的全局平均池化会将填充零位置也纳入平均，导致在存在缺失时特征被稀释。"
    "本文采用掩码感知池化，仅对有效位置进行平均："
)
pf.equation(doc, r"\bar{\mathbf{z}}_m = \frac{\sum_{t=1}^{50} M_m[t] \cdot \mathbf{Z}_m''[t]}{\max\left(\sum_{t=1}^{50} M_m[t], \epsilon\right)}")
pf.body(doc,
    "其中分母为有效位置的数量，epsilon为数值稳定小量，取10的负8次方。"
    "该池化方式确保当某模态存在连续缺失时，池化向量仅由剩余有效位置计算，"
    "不会因缺失而引入偏差。这是模型实现缺失鲁棒性的关键机制。"
)

pf.heading3(doc, "4.1.3 门控跨模态融合")
pf.body(doc,
    "获得三个模态的池化向量后，通过门控机制实现跨模态融合。"
    "对每个模态计算一个门控权重向量："
)
pf.equation(doc, r"\mathbf{g}_m = \sigma\left(\mathbf{W}_{g,m}[\bar{\mathbf{z}}_{text}; \bar{\mathbf{z}}_{audio}; \bar{\mathbf{z}}_{vision}] + \mathbf{b}_{g,m}\right)")
pf.body(doc,
    "门控权重sigmoid函数动态调节每个模态在融合中的贡献比例。"
    "最终融合表示为门控加权拼接后经线性变换和层归一化："
)
pf.equation(doc, r"\mathbf{h}_{fuse} = \mathrm{LayerNorm}\left(\mathrm{GELU}(\mathbf{W}_f[\mathbf{g}_{text}\cdot\bar{\mathbf{z}}_{text}; \mathbf{g}_{audio}\cdot\bar{\mathbf{z}}_{audio}; \mathbf{g}_{vision}\cdot\bar{\mathbf{z}}_{vision}] + \mathbf{b}_f)\right)")
pf.body(doc,
    "门控融合的优势在于：当某模态因缺失而质量下降时，门控机制可自动降低该模态的权重，"
    "转而依赖其他更可靠的模态。这一设计与缺失模态蒸馏的思路一致[4][9]。"
)

pf.heading3(doc, "4.1.4 双任务输出头")
pf.body(doc,
    "融合表示h_fuse同时输入两个任务头：分类头输出三维logits，经softmax后得到三分类概率；"
    "回归头输出一维标量，为情感强度的连续预测值。"
)
pf.equation(doc, r"\hat{\mathbf{y}}_{cls} = \mathrm{ClsHead}(\mathbf{h}_{fuse}) \in \mathbb{R}^{B \times 3}")
pf.equation(doc, r"\hat{y}_{reg} = \mathrm{RegHead}(\mathbf{h}_{fuse}) \in \mathbb{R}^{B}")

pf.heading2(doc, "4.2 目标函数与缺失增强训练")
pf.body(doc,
    "模型训练采用多任务联合损失。分类损失使用类别加权交叉熵，"
    "类别权重与训练集各类别频率成反比，以缓解正向样本偏多的不平衡问题。"
    "回归损失使用均方误差。总损失为两者加权和："
)
pf.equation(doc, r"\mathcal{L} = \lambda_{CE} \cdot \mathrm{CE}(\hat{\mathbf{y}}_{cls}, \mathbf{y}_{cls}; \mathbf{w}_{cls}) + \lambda_{MSE} \cdot \mathrm{MSE}(\hat{y}_{reg}, y_{reg})")
pf.body(doc,
    "其中分类损失权重lambda_CE取1.0，回归损失权重lambda_MSE取0.5。"
    "回归标签范围为负3到正3，MSE量级自然小于交叉熵，0.5的权重使两个损失项在量级上可比。"
)
pf.body(doc,
    "为提升模型对局部连续缺失的鲁棒性，本文在训练阶段引入缺失增强策略[2][5]。"
    "对每个训练批次中的样本，以概率p_aug=0.7随机选择一个模态，"
    "在该模态序列中随机生成一段连续缺失区间。区间长度L服从均匀分布，"
    "范围为5至25个对齐位置，对应总序列长度的10%至50%。"
    "缺失区间的起始位置s随机选择，确保区间不越界。"
    "将该区间内的特征全部置零，同时将对应有效性掩码置零。"
)
pf.equation(doc, r"L \sim \mathrm{Uniform}(5, 25), \quad s \sim \mathrm{Uniform}(0, 50-L)")
pf.body(doc,
    "缺失增强使模型在训练阶段就见到各种缺失模式，"
    "学会依赖未缺失的模态和位置做出预测，而非过拟合于完整数据的特定分布。"
    "缺失增强与掩码感知池化形成协同：增强阶段主动制造缺失，"
    "池化阶段通过掩码忽略缺失位置，两者共同确保模型在推理时面对真实缺失也能稳定预测。"
    "此外，缺失增强概率设为0.7而非1.0，是为了在每次训练迭代中保留部分完整样本，"
    "使模型同时学习完整和不完整两种条件下的预测策略，避免过度偏向缺失模式。"
)


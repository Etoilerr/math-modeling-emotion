pf.heading1(doc, "五、问题3——可解释性情感预测")

pf.heading2(doc, "5.1 A-EMN模型架构")
pf.body(doc,
    "本文在MA-MFN基础上提出注意力可解释多模态网络（Attention-based Explainable Multimodal Network, A-EMN），"
    "在保持单模态编码器和门控融合架构的同时，引入两级注意力机制："
    "模态级注意力用于量化各模态对预测的贡献程度，"
    "片段级注意力用于定位每个模态内部对预测最重要的时间位置。"
)

pf.heading3(doc, "5.1.1 模态级注意力")
pf.body(doc,
    "对每个模态的池化向量z_bar_m，使用共享的可学习查询向量q计算注意力分数，"
    "经softmax归一化后得到模态作用程度alpha_m[6]："
)
pf.equation(doc, r"\alpha_m = \frac{\exp(\mathbf{q}^{T} \mathbf{W}_q \bar{\mathbf{z}}_m)}{\sum_{m' \in \{text, audio, vision\}} \exp(\mathbf{q}^{T} \mathbf{W}_q \bar{\mathbf{z}}_{m'})}")
pf.body(doc,
    "三个模态的注意力权重之和为1。主要参考模态定义为权重最大的模态，"
    "即argmax_m alpha_m。alpha_m直接回答了模型在做预测时最依赖哪个模态的问题。"
)

pf.heading3(doc, "5.1.2 片段级注意力")
pf.body(doc,
    "在每个模态内部，对50个时间步的编码表示Z_m，使用可学习向量v计算片段级注意力："
)
pf.equation(doc, r"\beta_{m,t} = \frac{\exp(\mathbf{v}^{T} \mathbf{W}_v \mathbf{Z}_m''[t])}{\sum_{t'=1}^{50} \exp(\mathbf{v}^{T} \mathbf{W}_v \mathbf{Z}_m''[t'])}, \quad t=1,\dots,50")
pf.body(doc,
    "每个模态内的50个片段注意力权重之和为1。"
    "关键证据片段定义为beta_{m,t}最高的top-K个位置，"
    "这些位置对应模型认为对当前样本情感判断最重要的时间段。"
)

pf.heading3(doc, "5.1.3 注意力加权池化")
pf.body(doc,
    "在A-EMN中，掩码感知均值池化被替换为注意力加权池化："
)
pf.equation(doc, r"\tilde{\mathbf{z}}_m = \sum_{t=1}^{50} \beta_{m,t} \cdot M_m[t] \cdot \mathbf{Z}_m''[t]")
pf.body(doc,
    "该池化方式同时考虑了有效性掩码和片段重要性权重："
    "缺失或填充位置因掩码为零而不参与求和，"
    "高重要性位置获得更大权重。融合层和双任务头与MA-MFN相同。"
    "模型参数量为330,376，仅比MA-MFN增加516个注意力参数，"
    "在保持模型紧凑性的同时获得了可解释性。"
)

pf.heading2(doc, "5.2 关键证据回映方法")
pf.body(doc,
    "获得top-K关键证据位置后，需要将其映射回原始素材，使解释可被人类验证。"
    "文本模态：通过Q1建立的位置到词的映射表，将对齐位置i映射到对应的文本词片段，"
    "直接展示模型关注了哪些词语。语音模态：将对齐位置i映射到时间区间"
    "iT/50到(i+1)T/50，标注该时间段内的语音片段。视觉模态：将对齐位置i映射到对应时间区间，"
    "提取区间中间时刻的视频帧作为关键帧展示。这种从注意力权重到原始素材的双向映射，"
    "使模型解释不再是黑箱数字，而是可观察、可复核的证据[8]。"
    "在实际操作中，top-K的K值取5，即在50个位置中选取最重要的5个位置作为关键证据。"
    "这一选择在覆盖性和聚焦性之间取得平衡：K过小可能遗漏重要证据，"
    "K过大则稀释了解释的针对性。"
)

